-- ============================================================================
-- Distributed URL Shortener Service - Cross-Platform SQL Schema
-- Compatible with both PostgreSQL (production) and H2 (local / embedded)
-- ============================================================================

-- Distributed sequence table for ID allocation block leases
CREATE TABLE IF NOT EXISTS distributed_sequence (
    seq_name VARCHAR(64) PRIMARY KEY,
    current_val BIGINT NOT NULL
);

-- URL Mappings Table
CREATE TABLE IF NOT EXISTS url_mappings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_code VARCHAR(64) NOT NULL UNIQUE,
    original_url VARCHAR(2048) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP,
    is_custom BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    total_clicks BIGINT NOT NULL DEFAULT 0,
    created_by_ip VARCHAR(64)
);

-- Optimized Indexes for fast point lookups and range scans
CREATE INDEX IF NOT EXISTS idx_urls_short_code ON url_mappings (short_code);
CREATE INDEX IF NOT EXISTS idx_urls_created_at ON url_mappings (created_at);
CREATE INDEX IF NOT EXISTS idx_urls_active_code ON url_mappings (short_code, is_active);
